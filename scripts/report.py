"""Summarize the bounded paired study without manufacturing universal claims."""
import argparse
from collections import defaultdict
import json
import math
from pathlib import Path
import statistics
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

def read(path):return json.loads(path.read_text())

def summarize(folder):
    batch=read(folder/"batch.json")
    if not batch["complete"]:raise ValueError("Study is incomplete")
    groups=defaultdict(list)
    pairs=defaultdict(dict)
    records=[]
    for row in batch["results"]:
        result=dict(row)
        mode="closed" if row["mode"]=="reference" else row["mode"]
        first=row["first_success_step"]
        effective_steps=first or row["steps"]
        effective_calls=math.ceil(effective_steps/10) if mode=="closed" else 0
        result.update(evaluation_mode=mode,effective_steps=effective_steps,
                      effective_calls=effective_calls,
                      inference_seconds_to_outcome=sum(row["inference_seconds"][:effective_calls]))
        groups[(row["task_key"],row["condition"],mode)].append(result)
        pairs[(row["task_key"],row["initial_state_id"],row["condition"])][mode]=result
        records.append(result)
    table=[]
    for (task,condition,mode),rows in sorted(groups.items()):
        successful=[r for r in rows if r["success"]]
        table.append({"task":task,"condition":condition,"mode":mode,"n":len(rows),
                      "successes":sum(r["success"] for r in rows),
                      "mean_success_steps":statistics.mean(r["first_success_step"] for r in successful) if successful else None,
                      "mean_online_calls":statistics.mean(r["effective_calls"] for r in rows),
                      "mean_online_inference_seconds":statistics.mean(r["inference_seconds_to_outcome"] for r in rows)})
    paired=[]
    for (task,initial,condition),modes in sorted(pairs.items()):
        if set(modes)!={"closed","open"}:raise ValueError("Missing paired mode")
        closed,opened=modes["closed"],modes["open"]
        paired.append({"task":task,"initial_state_id":initial,"condition":condition,
                       "closed_success":closed["success"],"open_success":opened["success"],
                       "closed_first_success_step":closed["first_success_step"],
                       "open_first_success_step":opened["first_success_step"]})
    predictions=[]
    for path in folder.glob("*/predictions.jsonl"):
        predictions.extend(json.loads(line) for line in path.read_text().splitlines())
    latencies=[p["inference_seconds"] for p in predictions]
    result={"groups":table,"pairs":paired,"valid_episodes":batch["valid_trials"],
            "infrastructure_failures":batch["infrastructure_failures"],
            "model_inference_calls_measured":len(latencies),
            "inference_median_s":statistics.median(latencies),
            "inference_p95_s":sorted(latencies)[math.ceil(0.95*len(latencies))-1],
            "peak_gpu_allocated_bytes":max(p["peak_gpu_bytes"] for p in predictions),
            "reference_planning_costs":[{"trial":r["trial"],"full_plan_model_calls":r["policy_calls"],
                 "full_plan_inference_seconds":sum(r["inference_seconds"]),"full_plan_wall_seconds":r["wall_seconds"]}
                 for r in records if r["mode"]=="reference"],
            "claim_scope":"Three predefined LIBERO tasks and three fixed initial states; one checkpoint, seed, execution horizon and interruption. No universal ranking or reliability estimate.",
            "open_loop_definition":"Replay of a full nominal trajectory previously generated by closed-loop SmolVLA on this same initial state. Not a single-shot whole-task VLA plan.",
            "clean_control":"Clean replay is expected to match the nominal reference by construction; it is a reproducibility control, not independent evidence for equal general policy quality.",
            "timing":"Simulation pauses during synchronous inference. All modes retain the same low-level OSC feedback. Open online inference excludes nominal plan construction; full planning costs are listed separately.",
            "reference_semantics":"A reference records all 300 model-generated controls, including after first success, to provide a full common-budget replay plan. Evaluation uses first success and corresponding policy calls.",
            "selection":"Tasks, initial IDs and interruption interval were frozen before the interrupted outcomes; all valid outcomes retained."}
    return result

def write(folder,out):
    result=summarize(folder)
    out.mkdir(parents=True,exist_ok=False)
    (out/"summary.json").write_text(json.dumps(result,indent=2)+"\n")
    lines=["# Closed-loop feedback versus nominal open-loop replay\n\n",
        "Three manipulation tasks, three fixed initial states, two execution modes, clean and interrupted conditions: **36 valid episodes**. No policy training or scripted task trajectories.\n\n",
        "| Task | Condition | Closed success | Open success | Closed mean goal step, successes only | Open mean goal step, successes only |\n| --- | --- | --- | --- | --- | --- |\n"]
    lookup={(r["task"],r["condition"],r["mode"]):r for r in result["groups"]}
    for task in ["bowl","drawer","stove"]:
        for condition in ["clean","interrupted"]:
            a,b=lookup[(task,condition,"closed")],lookup[(task,condition,"open")]
            value=lambda r:"{:.1f}".format(r["mean_success_steps"]) if r["mean_success_steps"] is not None else "No success"
            lines.append("| {} | {} | {}/{} | {}/{} | {} | {} |\n".format(task,condition,a["successes"],a["n"],b["successes"],b["n"],value(a),value(b)))
    lines+=["\n## Paired outcomes\n\n",
      "| Task | Initial state | Condition | Closed goal step | Open goal step |\n| --- | --- | --- | --- | --- |\n"]
    for pair in result["pairs"]:
        lines.append("| {} | {} | {} | {} | {} |\n".format(pair["task"],pair["initial_state_id"],pair["condition"],
            pair["closed_first_success_step"] or "Timeout",pair["open_first_success_step"] or "Timeout"))
    lines+=["\n## Interpretation and limits\n\n"]
    for key in ["claim_scope","open_loop_definition","clean_control","timing","reference_semantics","selection"]:
        lines.append("- "+result[key]+"\n")
    lines.append("- The interruption withholds commands 30–39 inclusive, replaces their Cartesian components with zero, and preserves the previously executed gripper command. Simulation/controller feedback continue. Both modes receive the same intervention; there is no added recovery policy.\n")
    lines.append("- Success is LIBERO's simulator predicate, not valid inference or a controller acknowledgement. A first-attainment success is not a claim of sustained goal stability. Timeouts are not assigned invented completion times. Success-only means have different denominators when success rates differ.\n")
    lines.append("- Three selected initial states per task are too few for a general correlation or universal ordering. We do not search for extra cases just to obtain mixed results.\n")
    lines.append("\n## Inference and cost\n\nMeasured {} actual chunk calls: median {:.3f} s; p95 {:.3f} s; peak PyTorch GPU allocation {:.2f} GiB. Model-loading time and driver/context memory are additional. The model predicts 50 actions and executes ten before fresh inference; this horizon is fixed, not an ablation.\n".format(
        result["model_inference_calls_measured"],result["inference_median_s"],result["inference_p95_s"],
        result["peak_gpu_allocated_bytes"]/1024**3))
    lines.append("\nOpen-loop replay makes zero online model calls, but obtaining each nominal plan cost 30 VLA calls. See summary.json for every plan's wall/inference cost; zero online calls does not mean free end-to-end planning.\n")
    (out/"report.md").write_text("".join(lines))
    tasks=["bowl","drawer","stove"]
    fig,axes=plt.subplots(1,2,figsize=(9,3.8),sharey=True,constrained_layout=True)
    for ax,condition in zip(axes,["clean","interrupted"]):
        x=list(range(3))
        for offset,mode,color in [(-0.17,"closed","#22a78f"),(0.17,"open","#e49a45")]:
            values=[lookup[(task,condition,mode)]["successes"] for task in tasks]
            bars=ax.bar([i+offset for i in x],values,width=0.32,label=mode.capitalize(),color=color)
            for bar,value in zip(bars,values):
                ax.text(bar.get_x()+bar.get_width()/2,value+0.06,str(value)+"/3",ha="center",fontsize=10)
        ax.set_xticks(x,tasks);ax.set_ylim(0,3.7);ax.set_title(condition.capitalize())
        ax.set_yticks([0,1,2,3]);ax.spines[["top","right"]].set_visible(False)
    axes[0].set_ylabel("Successful episodes")
    axes[1].legend(frameon=False,loc="upper right")
    fig.suptitle("One pretrained VLA: feedback versus recorded nominal replay")
    fig.savefig(out/"success-by-task.png",dpi=160)
    plt.close(fig)
    print(json.dumps({k:v for k,v in result.items() if k in ["valid_episodes","inference_median_s","inference_p95_s"]}))
if __name__=="__main__":
    p=argparse.ArgumentParser();p.add_argument("--runs",type=Path,required=True);p.add_argument("--output",type=Path,required=True)
    a=p.parse_args();write(a.runs,a.output)
